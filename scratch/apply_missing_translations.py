def apply_translations(filepath, mapping):
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    for k, v in mapping.items():
        if k in data:
            data[k] = v
        else:
            data[k] = v # Add it anyway if missing just in case
            
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def main():
    apply_translations('assets/translations/ar.json', arabic_translations)
    apply_translations('assets/translations/en.json', english_translations)
    print("Successfully applied 153 missing translations to ar.json and en.json")

if __name__ == '__main__':
    main()
